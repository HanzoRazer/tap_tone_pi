def generate_html_report(
    session_meta: Dict[str, Any],
    spectrum_data: Dict[str, Any],
    peaks: List[Dict[str, float]],
    wood_properties: Optional[Dict[str, Any]] = None,
    coherence_stats: Optional[Dict[str, Any]] = None,
    output_path: Optional[str] = None
) -> str:
    """
    Generate an HTML report for tap tone analysis.

    Args:
        session_meta: Session metadata
        spectrum_data: Spectrum data (freq_hz, H_mag, coherence, phase_deg)
        peaks: List of detected peaks
        wood_properties: Estimated wood properties
        coherence_stats: Coherence quality statistics
        output_path: Optional path to save the report

    Returns:
        HTML string
    """
    # Generate charts as base64-encoded images
    spectrum_chart = _generate_spectrum_chart_base64(spectrum_data)
    coherence_chart = _generate_coherence_chart_base64(spectrum_data)

    # Build HTML
    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Tap Tone Analysis Report - {session_meta.get('specimen_id', 'Unknown')}</title>
    <style>
        {_get_css_styles()}
    </style>
</head>
<body>
    <div class="container">
        <header>
            <h1>🎸 Tap Tone Analysis Report</h1>
            <p class="subtitle">Generated {datetime.now().strftime('%Y-%m-%d %H:%M')}</p>
        </header>

        <section class="specimen-info">
            <h2>Specimen Information</h2>
            {_render_specimen_info(session_meta)}
        </section>

        <section class="spectrum">
            <h2>Transfer Function</h2>
            <div class="chart-container">
                <img src="data:image/png;base64,{spectrum_chart}" alt="Spectrum Chart">
            </div>
        </section>

        <section class="coherence">
            <h2>Coherence Analysis</h2>
            <div class="chart-container">
                <img src="data:image/png;base64,{coherence_chart}" alt="Coherence Chart">
            </div>
            {_render_coherence_stats(coherence_stats)}
        </section>

        <section class="peaks">
            <h2>Detected Resonance Peaks</h2>
            {_render_peaks_table(peaks)}
        </section>

        {_render_wood_properties(wood_properties) if wood_properties else ''}

        <footer>
            <p>Report generated by Tap Tone Analyzer v0.1.0</p>
            <p>Part of the tap_tone_pi project</p>
        </footer>
    </div>
</body>
</html>
"""

    if output_path:
        Path(output_path).write_text(html, encoding='utf-8')

    return html


