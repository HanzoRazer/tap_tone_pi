def _render_specimen_info(meta: Dict[str, Any]) -> str:
    """Render specimen information section."""
    dimensions = meta.get("dimensions_mm", {})

    items = [
        ("Specimen ID", meta.get("specimen_id", "Unknown")),
        ("Species", meta.get("species", "Unknown")),
        ("Grade", meta.get("grade", "-")),
        ("Length", f"{dimensions.get('length', '-')} mm"),
        ("Width", f"{dimensions.get('width', '-')} mm"),
        ("Thickness", f"{dimensions.get('thickness', '-')} mm"),
        ("Weight", f"{meta.get('weight_g', '-')} g"),
        ("Moisture", f"{meta.get('moisture_content_pct', '-')}%"),
    ]

    html = '<div class="info-grid">'
    for label, value in items:
        html += f"""
            <div class="info-item">
                <label>{label}</label>
                <span>{value}</span>
            </div>
        """
    html += '</div>'

    return html


def _render_coherence_stats(stats: Optional[Dict[str, Any]]) -> str:
    """Render coherence statistics."""
    if not stats:
        return ""

    grade = stats.get("quality_grade", "?")
    grade_class = f"grade-{grade.lower()}"

    return f"""
        <div class="stats-grid">
            <div class="stat-card">
                <div class="value">{stats.get('mean', 0):.3f}</div>
                <div class="label">Mean Coherence</div>
            </div>
            <div class="stat-card">
                <div class="value">{stats.get('min', 0):.3f}</div>
                <div class="label">Min Coherence</div>
            </div>
            <div class="stat-card">
                <div class="value">{stats.get('pct_above_threshold', 0):.1f}%</div>
                <div class="label">Above 0.9</div>
            </div>
            <div class="stat-card">
                <div class="value"><span class="grade {grade_class}">{grade}</span></div>
                <div class="label">Quality Grade</div>
            </div>
        </div>
    """


def _render_peaks_table(peaks: List[Dict[str, float]]) -> str:
    """Render peaks table."""
    if not peaks:
        return "<p>No peaks detected.</p>"

    html = """
        <table>
            <thead>
                <tr>
                    <th>#</th>
                    <th>Frequency (Hz)</th>
                    <th>Magnitude</th>
                    <th>Coherence</th>
                    <th>Mode</th>
                </tr>
            </thead>
            <tbody>
    """

    for i, peak in enumerate(peaks):
        coh = peak.get('coherence')
        coh_str = f"{coh:.3f}" if coh else "-"

        html += f"""
            <tr>
                <td>{i + 1}</td>
                <td>{peak.get('freq_hz', 0):.1f}</td>
                <td>{peak.get('magnitude', 0):.4f}</td>
                <td>{coh_str}</td>
                <td>{peak.get('mode', '-')}</td>
            </tr>
        """

    html += "</tbody></table>"
    return html


